int main() {
    // Безопасная настройка локализации кириллицы
#ifdef _WIN32
    SetConsoleCP(65001);
    SetConsoleOutputCP(65001);
#else
    setlocale(LC_ALL, "");
#endif

    int choice;
    double U, R, I;

    do {
        cout << "\n=== Проект: Калькулятор (Вариант 29) ===\n";
        cout << "1. Вычислить силу тока (I)\n";
        cout << "2. Вычислить электрическое сопротивление (R)\n";
        cout << "3. Вычислить электрическую мощность (P)\n";
        cout << "0. Выход из программы\n";
        cout << "---------------------------------------------\n";
        cout << "Выберите пункт: ";
        cin >> choice;

        switch (choice) {
        case 1:
            cout << "\n--- Расчет силы тока (I = U / R) ---\n";
            cout << "Введите напряжение U (в Вольтах, В): ";
            cin >> U;
            cout << "Введите сопротивление R (в Омах, Ом): ";
            cin >> R;
            cout << "---------------------------------------------\n";
            cout << "РЕЗУЛЬТАТ: Сила тока I = " << current(U, R) << " А (Ампер)\n";
            break;

        case 2:
            cout << "\n--- Расчет сопротивления (R = U / I) ---\n";
            cout << "Введите напряжение U (в Вольтах, В): ";
            cin >> U;
            cout << "Введите силу тока I (в Амперах, А): ";
            cin >> I;
            cout << "---------------------------------------------\n";
            cout << "РЕЗУЛЬТАТ: Сопротивление R = " << resistance(U, I) << " Ом\n";
            break;

        case 3:
            cout << "\n--- Расчет мощности (P = U * I) ---\n";
            cout << "Введите напряжение U (в Вольтах, В): ";
            cin >> U;
            cout << "Введите силу тока I (в Амперах, А): ";
            cin >> I;
            cout << "---------------------------------------------\n";
            cout << "РЕЗУЛЬТАТ: Электрическая мощность P = " << electricPower(U, I) << " Вт (Ватт)\n";
            break;

        case 0:
            cout << "\n[Программа успешно завершила работу.]\n";
            break;

        default:
            cout << "\n[Ошибка: Выбран некорректный пункт меню. Попробуйте снова!]\n";
        }
    } while (choice != 0);

    return 0;
}
